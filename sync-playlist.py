#!/usr/bin/env python3
"""Turn a public Spotify playlist into the launcher's music playlist.

Reads the track names from Spotify's public embed page, looks each one up on your own JioSaavnAPI
(github.com/cyberboysumanjay/JioSaavnAPI, running locally), and writes app/playlist.js, which
music.js plays instead of its built-in calm list.

    # terminal 1: start the API (in the JioSaavnAPI folder)
    pip3 install -r requirements.txt && python3 app.py
    # terminal 2: in webos-vibehack
    python3 sync-playlist.py https://open.spotify.com/playlist/<id>
    TV_HOST=192.168.1.50 ./install.sh

Options: --api http://localhost:5100 (where JioSaavnAPI runs), --shuffle.
"""
import argparse
import json
import os
import random
import re
import sys
import urllib.parse
import urllib.request

UA = {'User-Agent': 'Mozilla/5.0 (Macintosh) AppleWebKit/537.36 Chrome/130 Safari/537.36'}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'app', 'playlist.js')


def get(url, timeout=20):
    return urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=timeout).read().decode('utf-8')


def spotify_tracks(link):
    """(name, [(title, artist)]) from the playlist's public embed page, duplicates removed."""
    m = re.search(r'playlist[/:]([A-Za-z0-9]{22})', link)
    if not m:
        sys.exit('Not a Spotify playlist link: ' + link)
    html = get('https://open.spotify.com/embed/playlist/' + m.group(1))
    data = re.search(r'<script id="__NEXT_DATA__"[^>]*>(.*?)</script>', html, re.S)
    if not data:
        sys.exit('Could not read the playlist. Is it public?')
    entity = json.loads(data.group(1))['props']['pageProps']['state']['data']['entity']
    seen, tracks = set(), []
    for t in entity.get('trackList', []):
        key = (t.get('title', '').lower(), t.get('subtitle', '').lower())
        if t.get('title') and key not in seen:
            seen.add(key)
            tracks.append((t['title'], t.get('subtitle', '')))
    return entity.get('name', 'Playlist'), tracks


def clean_title(title):
    """Drop decorations like '- Acoustic' or '(feat. X)' that hurt search matches."""
    title = re.sub(r'\s*[\(\[].*?(feat|with|from|ft\.).*?[\)\]]', '', title, flags=re.I)
    return re.sub(r'\s+-\s+.*$', '', title).strip() or title


def unescape(s):
    return (s or '').replace('&amp;', '&').replace('&quot;', '"').replace('&#039;', "'")


def find(api, title, artist):
    first_artist = artist.split(',')[0].strip()
    for query in (clean_title(title) + ' ' + first_artist, clean_title(title)):
        try:
            res = json.loads(get(api + '/song/?query=' + urllib.parse.quote(query)))
        except Exception:
            continue
        for s in res if isinstance(res, list) else []:
            if s.get('media_url'):
                return {'title': unescape(s.get('song')) or title,
                        'artist': unescape(s.get('primary_artists') or s.get('singers')) or artist,
                        'src': s['media_url']}
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('playlist', help='Spotify playlist link (must be public)')
    ap.add_argument('--api', default='http://localhost:5100', help='JioSaavnAPI address')
    ap.add_argument('--shuffle', action='store_true', help='shuffle the order')
    args = ap.parse_args()
    api = args.api.rstrip('/')

    try:
        get(api + '/', timeout=5)
    except Exception:
        sys.exit('JioSaavnAPI is not running at %s. Start it first: cd ~/Documents/Projects/JioSaavnAPI '
                 '&& python3 app.py' % api)

    name, tracks = spotify_tracks(args.playlist)
    print('%s: %d songs' % (name, len(tracks)))
    found, missing = [], []
    for i, (title, artist) in enumerate(tracks, 1):
        song = find(api, title, artist)
        print('  [%d/%d] %s %s — %s' % (i, len(tracks), 'ok  ' if song else 'MISS', title, artist))
        (found.append(song) if song else missing.append('%s — %s' % (title, artist)))
    if args.shuffle:
        random.shuffle(found)
    if not found:
        sys.exit('No songs found; nothing written.')

    with open(OUT, 'w') as f:
        f.write('// Generated by sync-playlist.py from Spotify playlist "%s". Re-run it to update.\n' % name)
        f.write('window.PLAYLIST = ' + json.dumps(found, indent=1, ensure_ascii=False) + ';\n')
    print('\nWrote %d songs to app/playlist.js.' % len(found))
    if missing:
        print('Not found on JioSaavn (%d): %s' % (len(missing), '; '.join(missing)))
    print('Now install: TV_HOST=<tv ip> ./install.sh')


if __name__ == '__main__':
    main()
